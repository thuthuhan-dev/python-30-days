#Here are examples of different Python data types:
# Number
# Integer
print(10)
print(type(10))

# Float
print(9.8)
print(type(9.8))

# Complex
print(4 - 4j)
print(type(4 - 4j))

# String
print('Thu Thu')
print(type('Thu Thu'))

# Boolean
print(True)
print(type(True))

# List
print(['Thu Thu', 'Python', 'Myanmar'])
print(type(['Thu Thu', 'Python', 'Myanmar']))

# Tuple
print((1, 2, 3))
print(type((1, 2, 3)))

# Set
print({3, 1, 2})
print(type({3, 1, 2}))

# Dictionary
print({'name': 'Thu Thu', 'age': 21})
print(type({'name': 'Thu Thu', 'age': 21}))

# Euclidean distance between (2, 3) and (10, 8)
x1, y1 = 2, 3
x2, y2 = 10, 8
distance = ((x2 - x1) ** 2 + (y2 - y1) ** 2) ** 0.5
print(distance)